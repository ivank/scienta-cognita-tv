    fun find(name: String?): Coordinates? {
        if (name.isNullOrBlank()) return null
        val lower = name.trim().lowercase(Locale.ROOT)
        exactLocations[lower]?.let { return it }

        for ((key, coord) in keywords) {
            if (lower.contains(key)) return coord
        }
        return null
    }

    fun fromMedia(media: AerialMedia?): Coordinates? {
        if (media == null) return null
        // 1. Check EXIF GPS data if available
        val lat = media.metadata.exif.latitude
        val lon = media.metadata.exif.longitude
        if (lat != null && lon != null && (lat != 0.0 || lon != 0.0)) {
            return Coordinates(lat, lon)
        }

        // 2. Try shortDescription
        find(media.metadata.shortDescription)?.let { return it }

        // 3. Try title
        find(media.metadata.title)?.let { return it }

        // 4. Try any POI
        for (poi in media.metadata.pointsOfInterest.values) {
            find(poi)?.let { return it }
        }

        return null
    }
